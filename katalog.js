document.addEventListener('DOMContentLoaded', () => {
  const container = document.getElementById('pestGridContainer');
  const searchInput = document.getElementById('searchInput');
  const commoditySelect = document.getElementById('commoditySelect');
  const tagButtons = document.querySelectorAll('.tag-btn');

  let activeCategory = 'all';
  let searchQuery = '';

  function renderPests() {
    container.innerHTML = '';
    const pestArray = Object.values(pestDatabase);

    const filtered = pestArray.filter(pest => {
      const matchSearch = pest.name.toLowerCase().includes(searchQuery) || 
                          pest.latin.toLowerCase().includes(searchQuery) ||
                          pest.desc.toLowerCase().includes(searchQuery);
      const matchCategory = (activeCategory === 'all') || (pest.cat === activeCategory);
      return matchSearch && matchCategory;
    });

    if (filtered.length === 0) {
      container.innerHTML = '<div class="no-results">Tidak ada hama yang sesuai dengan kriteria pencarian.</div>';
      return;
    }

    filtered.forEach(pest => {
      const card = document.createElement('article');
      card.className = 'pest-card';
      card.innerHTML = `
        <div class="card-img-wrapper">
          <img src="${pest.img}" alt="${pest.name}">
        </div>
        <div class="card-content">
          <span class="card-tag">${pest.tag}</span>
          <h3 class="card-name">${pest.name}</h3>
          <p class="card-latin">${pest.latin}</p>
          <p class="card-desc">${pest.desc}</p>
          <a href="detail-hama.html?id=${pest.id}" class="card-link">
            Lihat Detail Hama <span>&rarr;</span>
          </a>
        </div>
      `;
      container.appendChild(card);
    });
  }

  // Event Input Pencarian
  searchInput.addEventListener('input', (e) => {
    searchQuery = e.target.value.toLowerCase().trim();
    renderPests();
  });

  // Event Dropdown Komoditas
  commoditySelect.addEventListener('change', (e) => {
    activeCategory = e.target.value;
    tagButtons.forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-cat') === activeCategory);
    });
    renderPests();
  });

  // Event Tombol Kategori Cepat
  tagButtons.forEach(btn => {
    btn.addEventListener('click', () => {
      tagButtons.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      activeCategory = btn.getAttribute('data-cat');
      commoditySelect.value = activeCategory;
      renderPests();
    });
  });

  renderPests();
});